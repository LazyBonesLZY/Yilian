        val t4 = (w2 ushr 2).toInt()
        val v11 = (((v3 ushr 8) and 0xFF) or (v9 shl 8)) xor v9 xor
            (((v3 and 0xFFFF) ushr 2) or (v9 shl 14)) xor t3 xor t4
        c[0] = sbox(v10)
        c[1] = sbox(v11)
        return v4
    }

