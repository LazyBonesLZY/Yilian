        val v1 = c[1]
        val v2 = c[3] + c[0]
        val v3 = c[4] xor v1
        val v4 = (c[0] xor c[2]) + v1
        val v5 = (v2 shl 16) or (v3 ushr 16)
        val v6 = v2 ushr 14
        val v7 = v2 ushr 6
        val v8 = v2 ushr 16
        val v9 = (v3 shl 16) or (v2 ushr 16)
        val w1 = pack(v3 ushr 16, v5)
        val t1 = (w1 ushr 14).toInt()
        val t2 = (w1 ushr 8).toInt()
        val v10 = ((v6 and 3) or (v5 shl 2)) xor v5 xor ((v7 and 0x3FF) or (v5 shl 10)) xor t1 xor t2
        val w2 = pack(v8, v9)
