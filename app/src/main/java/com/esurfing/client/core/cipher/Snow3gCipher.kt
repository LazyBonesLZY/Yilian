/**
 * 07E824B2-9E5C-4D1B-BBB0-5E07C251E4AA：SNOW3G 变体流密码。
 * 22 个状态寄存 + FSM（两张 S 盒），16 个 s-cell 初始化后跑 32 轮热身，
 * 然后逐字异或密钥流。加解密完全对称，输入零填充到 4 字节对齐。
 * 逐行译自 C 版（sub_229C 密钥调度 / sub_427C FSM / sub_20F8 密钥流），
 * 包括其中看上去奇怪的位操作，不要“修正”成标准 SNOW3G。
 */
internal class Snow3gVariantCipher(key: ByteArray, iv: ByteArray) : SessionCipher {

    private val key = key.copyOf(16)
    private val iv = iv.copyOf(16)

    override fun encrypt(text: String): String {
        val data = text.toByteArray(Charsets.UTF_8)
        val total = if (data.size % 4 == 0) data.size else data.size + (4 - data.size % 4)
        val buf = ByteArray(total)
        data.copyInto(buf)
        apply(buf)
        return buf.toHexUpper()
    }

    override fun decrypt(hex: String): String? {
        val data = hex.hexToBytesOrNull() ?: return null
        val buf = data.copyOf()
        apply(buf)
        return buf.stripZeroTailToString()
    }

    private fun apply(buf: ByteArray) {
        val c = IntArray(CELLS)
        keySchedule(c)
        generate(c, buf)
    }

