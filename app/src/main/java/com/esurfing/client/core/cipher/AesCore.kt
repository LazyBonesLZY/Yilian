    private val RC = intArrayOf(0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36)

    private fun xtime(x: Int): Int {
        val v = (x shl 1) and 0xFF
        return if (x and 0x80 != 0) v xor 0x1B else v
    }

    private fun mul(a: Int, b: Int): Int {
        var x = a and 0xFF
        var y = b and 0xFF
        var p = 0
        for (i in 0 until 8) {
            if (y and 1 != 0) p = p xor x
            val hi = x and 0x80
            x = (x shl 1) and 0xFF
            if (hi != 0) x = x xor 0x1B
            y = y ushr 1
        }
        return p and 0xFF
    }

    /** sub_1FA0: 自定义密钥扩展，产出 176 字节轮密钥。 */
