    /** sub_27F0: 单块加密，输入/输出按列优先，内部状态按行优先。 */
    fun encryptBlock(sk: IntArray, input: ByteArray, inOffset: Int, output: ByteArray, outOffset: Int) {
        val s = IntArray(16)
        for (r in 0 until 4) for (c in 0 until 4) s[r * 4 + c] = input[inOffset + c * 4 + r].toInt() and 0xFF
        for (i in 0 until 16) s[i] = s[i] xor sk[i]
        for (rnd in 1..10) {
            for (i in 0 until 16) s[i] = S[s[i]]
            val t = IntArray(16)
            for (r in 0 until 4) for (c in 0 until 4) t[r * 4 + c] = s[r * 4 + ((c + r) and 3)]
            t.copyInto(s)
            if (rnd < 10) {
                for (c in 0 until 4) {
                    val a0 = s[c]; val a1 = s[4 + c]; val a2 = s[8 + c]; val a3 = s[12 + c]
                    s[c] = xtime(a0) xor (xtime(a1) xor a1) xor a2 xor a3
                    s[4 + c] = a0 xor xtime(a1) xor (xtime(a2) xor a2) xor a3
                    s[8 + c] = a0 xor a1 xor xtime(a2) xor (xtime(a3) xor a3)
                    s[12 + c] = (xtime(a0) xor a0) xor a1 xor a2 xor xtime(a3)
                }
            }
            for (i in 0 until 16) s[i] = s[i] xor sk[16 * rnd + i]
        }
        for (r in 0 until 4) for (c in 0 until 4) output[outOffset + c * 4 + r] = s[r * 4 + c].toByte()
    }

    /** 标准逆轮函数解密。 */
    fun decryptBlock(sk: IntArray, input: ByteArray, inOffset: Int, output: ByteArray, outOffset: Int) {
        val s = IntArray(16)
        for (r in 0 until 4) for (c in 0 until 4) s[r * 4 + c] = input[inOffset + c * 4 + r].toInt() and 0xFF
        for (i in 0 until 16) s[i] = s[i] xor sk[160 + i]
        for (rnd in 9 downTo 1) {
            val t = IntArray(16)
            for (r in 0 until 4) for (c in 0 until 4) t[r * 4 + c] = s[r * 4 + ((c - r + 4) and 3)]
            t.copyInto(s)
            for (i in 0 until 16) s[i] = INV_S[s[i]]
            for (i in 0 until 16) s[i] = s[i] xor sk[16 * rnd + i]
            for (c in 0 until 4) {
                val a0 = s[c]; val a1 = s[4 + c]; val a2 = s[8 + c]; val a3 = s[12 + c]
                s[c] = mul(0x0e, a0) xor mul(0x0b, a1) xor mul(0x0d, a2) xor mul(0x09, a3)
                s[4 + c] = mul(0x09, a0) xor mul(0x0e, a1) xor mul(0x0b, a2) xor mul(0x0d, a3)
                s[8 + c] = mul(0x0d, a0) xor mul(0x09, a1) xor mul(0x0e, a2) xor mul(0x0b, a3)
                s[12 + c] = mul(0x0b, a0) xor mul(0x0d, a1) xor mul(0x09, a2) xor mul(0x0e, a3)
            }
        }
        val t = IntArray(16)
        for (r in 0 until 4) for (c in 0 until 4) t[r * 4 + c] = s[r * 4 + ((c - r + 4) and 3)]
        t.copyInto(s)
        for (i in 0 until 16) s[i] = INV_S[s[i]]
        for (i in 0 until 16) s[i] = s[i] xor sk[i]
        for (r in 0 until 4) for (c in 0 until 4) output[outOffset + c * 4 + r] = s[r * 4 + c].toByte()
    }
