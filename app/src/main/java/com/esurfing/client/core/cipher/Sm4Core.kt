    /** @param forward true 为加密轮密钥，false 为解密（反序）。 */
    fun keySchedule(key: ByteArray, forward: Boolean): IntArray {
        val k = IntArray(4) { readBe32(key, it * 4) xor FK[it] }
        val rk = IntArray(32)
        for (i in 0 until 32) {
            val t = k[1] xor k[2] xor k[3] xor CK[i]
            val s0 = S[(t ushr 24) and 0xFF]
            val s1 = S[(t ushr 16) and 0xFF]
            val s2 = S[(t ushr 8) and 0xFF]
            val s3 = S[t and 0xFF]
            val w4 = (s0 shl 24) or (s1 shl 16)
            val w1 = w4 or (s2 shl 8)
            val b = w1 or s3
            val e1 = (b shl 13) or (w4 ushr 19)
            val e2 = (b shl 23) or (w1 ushr 9)
            rk[i] = b xor k[0] xor e1 xor e2
            k[0] = k[1]; k[1] = k[2]; k[2] = k[3]; k[3] = rk[i]
        }
        if (!forward) {
            for (i in 0 until 16) {
                val t = rk[i]
                rk[i] = rk[31 - i]
                rk[31 - i] = t
            }
        }
        return rk
    }

    /** sub_1FA0：单块正向变换（加解密同一个函数）。 */
    fun processBlock(rk: IntArray, input: ByteArray, inOffset: Int, output: ByteArray, outOffset: Int) {
        val x = IntArray(4) { readBe32(input, inOffset + it * 4) }
        val store = IntArray(32)
        for (i in 0 until 32) {
            val t = x[1] xor x[2] xor x[3] xor rk[i]
            val s0 = S[(t ushr 24) and 0xFF]
            val s1 = S[(t ushr 16) and 0xFF]
            val s2 = S[(t ushr 8) and 0xFF]
            val s3 = S[t and 0xFF]
            val w4 = (s0 shl 24) or (s1 shl 16)
            val w1 = w4 or (s2 shl 8)
            val b = w1 or s3
            val e0 = (s0 ushr 6) or ((b and 0x3FFFFFFF) shl 2)
            val e1 = (b shl 24) or (w1 ushr 8)
            val e2 = (b shl 10) or (w4 ushr 22)
            val e3 = (b shl 18) or (w1 ushr 14)
            val nx = b xor x[0] xor e1 xor e0 xor e2 xor e3
            store[i] = nx
            x[0] = x[1]; x[1] = x[2]; x[2] = x[3]; x[3] = nx
        }
        writeBe32(output, outOffset, store[31])
        writeBe32(output, outOffset + 4, store[30])
        writeBe32(output, outOffset + 8, store[29])
        writeBe32(output, outOffset + 12, store[28])
    }
